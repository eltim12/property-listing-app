#!/usr/bin/env node
/**
 * Switch frontend + backoffice between local and deployed API.
 *
 * Usage:
 *   node scripts/set-api-target.mjs local
 *   node scripts/set-api-target.mjs deployed
 *   node scripts/set-api-target.mjs status
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const configPath = path.join(root, "api.config.json");

function loadConfig() {
  return JSON.parse(fs.readFileSync(configPath, "utf8"));
}

function saveConfig(config) {
  fs.writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`);
}

function writeEnvFiles(config) {
  const target = config.target;
  const apiUrl = config.targets[target];
  if (!apiUrl) {
    throw new Error(`Unknown target "${target}". Use: ${Object.keys(config.targets).join(", ")}`);
  }

  const frontendEnv = `# Generated by scripts/set-api-target.mjs — do not edit by hand
# Active target: ${target}
NEXT_PUBLIC_API_TARGET=${target}
NEXT_PUBLIC_API_URL=${apiUrl}
`;

  const backofficeEnv = `# Generated by scripts/set-api-target.mjs — do not edit by hand
# Active target: ${target}
VITE_API_TARGET=${target}
VITE_API_ORIGIN=${apiUrl}
VITE_API_BASE_URL=${apiUrl}/api
`;

  fs.writeFileSync(path.join(root, "frontend", ".env.local"), frontendEnv);
  fs.writeFileSync(path.join(root, "backoffice", ".env"), backofficeEnv);

  return { target, apiUrl };
}

const arg = (process.argv[2] || "status").toLowerCase();
const config = loadConfig();

if (arg === "status") {
  const apiUrl = config.targets[config.target];
  console.log(`API target: ${config.target}`);
  console.log(`API URL:    ${apiUrl}`);
  console.log(`Switch with: npm run api:local  |  npm run api:deployed`);
  process.exit(0);
}

if (!config.targets[arg]) {
  console.error(`Unknown target "${arg}". Available: ${Object.keys(config.targets).join(", ")}`);
  process.exit(1);
}

config.target = arg;
saveConfig(config);
const { target, apiUrl } = writeEnvFiles(config);
console.log(`Switched API target → ${target}`);
console.log(`API URL: ${apiUrl}`);
console.log(`Updated: frontend/.env.local, backoffice/.env, api.config.json`);
console.log(`Restart frontend / backoffice dev servers for the change to apply.`);
